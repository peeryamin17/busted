/**
 * Tests for the PayloadsAllTheThings extraction (scripts/extract-payloads.ts).
 * No network, no DB, no LLM. Reads the source zip and the generated data
 * under backend/data/payloads and checks: manifest integrity (hashes match
 * the zip), pack caps and budgets, the dotdotpwn exclusion, playbook chunk
 * shape, signature hygiene (no key material), and byte-identical output on
 * a re-run.
 *
 * Run:  npx tsx test/payloads-extract.test.ts   (from backend/)
 *
 * The zip lives at ~/workspace/user/files/PayloadsAllTheThings-master.zip
 * by default; override with $PAYLOADS_ZIP.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import JSZip from 'jszip';
import { runExtraction } from '../scripts/extract-payloads.js';

let failures = 0;
let passes = 0;
function check(name: string, cond: boolean, extra?: unknown): void {
  if (!cond) { failures++; console.error(`FAIL: ${name}`, extra ?? ''); }
  else { passes++; console.log(`ok: ${name}`); }
}

const DATA_DIR = resolve(__dirname, '..', 'data', 'payloads');
const ZIP_PATH = process.env.PAYLOADS_ZIP
  ?? join(homedir(), 'workspace', 'user', 'files', 'PayloadsAllTheThings-master.zip');
const ZIP_PREFIX = 'PayloadsAllTheThings-master/';
const MAX_PACK_BYTES = 20 * 1024;

interface ManifestEntry {
  id: string;
  kind: string;
  file: string | null;
  source: string;
  sourceSha256: string;
  sourceBytes: number;
  sourceLines: number;
  bytes: number | null;
  lines: number | null;
  budget: { maxRequestsPerEndpoint: number | null; note: string };
  chunkIndex?: number;
  chunkCount?: number;
  excludedReason?: string;
}

interface Manifest {
  generatedBy: string;
  version: number;
  archive: { file: string; sha256: string; files: number; bytes: number };
  license: string;
  packs: ManifestEntry[];
}

function sha256(buf: Buffer): string {
  return createHash('sha256').update(buf).digest('hex');
}

function splitLines(text: string): string[] {
  return text.replace(/\r\n/g, '\n').replace(/\r/g, '\n').split('\n');
}

/** Line count the way wc -l counts: newlines, not split elements. */
function countLines(text: string): number {
  if (text === '') return 0;
  const parts = splitLines(text);
  return parts[parts.length - 1] === '' ? parts.length - 1 : parts.length;
}

async function main(): Promise<void> {
  check('source zip exists', existsSync(ZIP_PATH), ZIP_PATH);
  if (!existsSync(ZIP_PATH)) throw new Error(`zip not found: ${ZIP_PATH}`);

  const zipBuf = readFileSync(ZIP_PATH);
  const zip = await JSZip.loadAsync(zipBuf);
  const zipText = async (rel: string): Promise<string> => {
    const entry = zip.file(ZIP_PREFIX + rel);
    if (!entry) throw new Error(`missing from archive: ${rel}`);
    return (await entry.async('nodebuffer')).toString('utf8').replace(/^\uFEFF/, '');
  };
  const zipBufOf = async (rel: string): Promise<Buffer> => {
    const entry = zip.file(ZIP_PREFIX + rel);
    if (!entry) throw new Error(`missing from archive: ${rel}`);
    return entry.async('nodebuffer');
  };

  const manifest = JSON.parse(readFileSync(join(DATA_DIR, 'manifest.json'), 'utf8')) as Manifest;
  check('manifest generated by the extractor', manifest.generatedBy === 'scripts/extract-payloads.ts');
  check('manifest license names Swissky MIT', manifest.license.includes('MIT') && manifest.license.includes('Swissky'));
  check('manifest archive sha256 matches the zip', manifest.archive.sha256 === sha256(zipBuf));
  check('manifest archive file count matches the zip', manifest.archive.files === Object.values(zip.files).filter((f) => !f.dir).length);
  check('NOTICE.md carries the MIT attribution', readFileSync(join(DATA_DIR, 'NOTICE.md'), 'utf8').includes('Copyright (c) 2019 Swissky'));

  const packs = manifest.packs.filter((p) => p.kind !== 'excluded');
  const excluded = manifest.packs.filter((p) => p.kind === 'excluded');
  check('one pack excluded', excluded.length === 1 && excluded[0].id === 'dotdotpwn');
  check('excluded pack has a reason and no file', !!excluded[0].excludedReason && excluded[0].file === null);
  check('no dotdotpwn file shipped', !readdirSync(join(DATA_DIR, 'packs')).some((f) => f.includes('dotdotpwn')));

  // Every listed pack: file exists, size/line counts match, under the cap,
  // source hash matches the zip, budget present.
  for (const p of packs) {
    const full = join(DATA_DIR, p.file as string);
    check(`pack file exists: ${p.id}`, existsSync(full));
    if (!existsSync(full)) continue;
    const buf = readFileSync(full);
    check(`pack bytes match manifest: ${p.id}`, buf.length === p.bytes, { manifest: p.bytes, actual: buf.length });
    // Manifest lines are content lines: for playbook chunks the 2 header
    // lines (comment + blank) are not counted.
    const counted = p.kind === 'playbook-chunk' ? countLines(buf.toString('utf8')) - 2 : countLines(buf.toString('utf8'));
    check(`pack lines match manifest: ${p.id}`, counted === p.lines, { manifest: p.lines, counted });
    check(`pack under 20 KB cap: ${p.id}`, (p.bytes ?? 0) <= MAX_PACK_BYTES, p.bytes);
    const firstSource = p.source.split(', ')[0];
    const sourceBuf = await zipBufOf(firstSource);
    check(`pack source hash matches zip: ${p.id}`, sha256(sourceBuf) === p.sourceSha256);
    check(`pack source bytes match zip: ${p.id}`, sourceBuf.length === p.sourceBytes);
  }
  for (const p of packs.filter((x) => x.kind === 'micro-pack')) {
    check(`micro-pack has a ladder budget: ${p.id}`, typeof p.budget.maxRequestsPerEndpoint === 'number' && p.budget.maxRequestsPerEndpoint > 0 && p.budget.maxRequestsPerEndpoint <= 50);
  }
  for (const p of packs.filter((x) => x.kind === 'playbook-chunk')) {
    check(`playbook chunk is retrieval-only: ${p.id}`, p.budget.maxRequestsPerEndpoint === null);
    check(`playbook chunk within 120 lines: ${p.id}`, (p.lines ?? 0) <= 120, p.lines);
  }

  // Playbook chunks: header cites source and chunk n/N; chunk counts line
  // up; first chunk starts at the source's first line.
  const chunkGroups = new Map<string, ManifestEntry[]>();
  for (const p of packs.filter((x) => x.kind === 'playbook-chunk')) {
    const key = p.source;
    if (!chunkGroups.has(key)) chunkGroups.set(key, []);
    chunkGroups.get(key)?.push(p);
  }
  check('all 17 playbook sources chunked', chunkGroups.size === 17, chunkGroups.size);
  for (const [source, chunks] of chunkGroups) {
    chunks.sort((a, b) => (a.chunkIndex ?? 0) - (b.chunkIndex ?? 0));
    const total = chunks[0].chunkCount ?? 0;
    check(`chunks contiguous 1..N for ${source}`, chunks.length === total && chunks.every((c, i) => c.chunkIndex === i + 1));
    const sourceLines = splitLines(await zipText(source));
    const firstChunk = readFileSync(join(DATA_DIR, chunks[0].file as string), 'utf8');
    check(`chunk header cites source: ${source}`, firstChunk.startsWith(`<!-- source: ${source} | chunk 1/${total}`));
    const firstContent = splitLines(firstChunk).slice(2).find((l) => l.trim() !== '');
    const firstSource = sourceLines.find((l) => l.trim() !== '');
    check(`first chunk starts at source start: ${source}`, firstContent === firstSource);
  }

  // Signatures: regexes compile, no key material, paths/sinks verbatim.
  const secrets = JSON.parse(readFileSync(join(DATA_DIR, 'signatures', 'secrets.json'), 'utf8')) as {
    machineKey: { attributePatterns: { pattern: string }[] };
    hardcodedAssignment: { patterns: { pattern: string; flags?: string }[] };
  };
  for (const p of secrets.machineKey.attributePatterns) {
    check(`secret regex compiles: ${p.pattern.slice(0, 40)}`, (() => { try { new RegExp(p.pattern); return true; } catch { return false; } })());
  }
  for (const p of secrets.hardcodedAssignment.patterns) {
    check(`secret regex compiles: ${p.pattern.slice(0, 40)}`, (() => { try { new RegExp(p.pattern, p.flags); return true; } catch { return false; } })());
  }
  const secretsText = readFileSync(join(DATA_DIR, 'signatures', 'secrets.json'), 'utf8');
  check('secrets.json holds no 40+ hex run (no key material)', !/[0-9A-Fa-f]{40,}/.test(secretsText));
  const machineKeysText = await zipText('API Key Leaks/Files/MachineKeys.txt');
  const leakedLine = splitLines(machineKeysText).find((l) => l.trim() !== '' && secretsText.includes(l.trim()));
  check('no MachineKeys.txt value appears in secrets.json', leakedLine === undefined, leakedLine?.slice(0, 40));

  const scm = JSON.parse(readFileSync(join(DATA_DIR, 'signatures', 'scm-exposure.json'), 'utf8')) as {
    paths: { path: string; system: string; source: string; verbatim: boolean; note?: string }[];
  };
  check('scm list is non-empty', scm.paths.length > 0);
  for (const entry of scm.paths) {
    if (entry.verbatim) {
      const doc = await zipText(entry.source);
      check(`verbatim scm path in its doc: ${entry.path}`, doc.includes(entry.path));
    } else {
      check(`derived scm path carries a note: ${entry.path}`, !!entry.note);
    }
  }

  const sinks = JSON.parse(readFileSync(join(DATA_DIR, 'signatures', 'deserialization-sinks.json'), 'utf8')) as {
    sinks: { name: string; language: string; source: string }[];
  };
  check('sink list is non-empty', sinks.sinks.length > 0);
  const sinkDocs = new Set(sinks.sinks.map((s) => s.source));
  check('every sink doc yielded at least one sink', sinkDocs.size === 5, [...sinkDocs]);
  for (const s of sinks.sinks) {
    const doc = await zipText(s.source);
    // Operator/function names are checked without trailing "()" noise.
    const needle = s.name.replace(/\(\)$/, '').replace(/\(.*$/, '');
    check(`sink named in its doc: ${s.name}`, doc.includes(needle) || doc.includes(s.name));
  }

  // Determinism: re-extract into a temp dir and compare byte-for-byte.
  const tmp = mkdtempSync(join(tmpdir(), 'payloads-test-'));
  try {
    await runExtraction({ zipPath: ZIP_PATH, outDir: tmp });
    const collect = (dir: string, base = ''): string[] => {
      const out: string[] = [];
      for (const name of readdirSync(dir).sort()) {
        const full = join(dir, name);
        out.push(...(statSync(full).isDirectory() ? collect(full, `${base}${name}/`) : [`${base}${name}`]));
      }
      return out;
    };
    const committed = collect(DATA_DIR).filter((f) => f !== 'README.md');
    const fresh = collect(tmp);
    check('re-run produces the same file set', JSON.stringify(committed) === JSON.stringify(fresh), { committed: committed.length, fresh: fresh.length });
    for (const f of committed) {
      const a = readFileSync(join(DATA_DIR, f));
      const b = readFileSync(join(tmp, f));
      check(`re-run byte-identical: ${f}`, a.equals(b));
    }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  if (failures > 0) { console.error(`${failures} payloads-extract test(s) failed, ${passes} passed`); process.exit(1); }
  console.log(`ALL PAYLOADS-EXTRACT TESTS PASSED (${passes} checks)`);
  process.exit(0);
}

main().catch((e) => { console.error('payloads-extract test crashed', e); process.exit(1); });
