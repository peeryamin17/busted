import type { Finding, Scan } from '../types.js';
import { SEVERITY_ORDER } from '../types.js';
import type { CoverageSummary } from '../coverage/ledger.js';
import { coverageVerdict, emptyCoverageVerdict, zeroFindingsLines } from './coverageHonesty.js';
import { splitWhiteBoxFindings, WHITEBOX_SECTION_NOTE } from './whitebox.js';
import { chainLines, hintFindings, verifiedFindings, verificationLabel } from './verification.js';
import { buildDefensiveSection, defensiveClassesFromFindings } from './defensive.js';
import { gradingNotes } from './gradeFindings.js';

export interface ReportInput {
  scan: Scan;
  findings: Finding[];
  generatedBy: string;
  /** Absent means no coverage data: the report treats the surface as unexamined. */
  coverage?: CoverageSummary;
}

/** Markdown report, the free-tier format and the base for bounty-platform templates. */
export function generateMarkdownReport(input: ReportInput): string {
  const { scan, findings } = input;
  const sorted = [...findings].sort(
    (a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity]
  );
  const counts: Record<string, number> = {};
  for (const f of sorted) counts[f.severity] = (counts[f.severity] ?? 0) + 1;

  const lines: string[] = [
    '# BugSeek AI — Security Assessment Report',
    '',
    `- **Target:** ${scan.targetUrl}`,
    `- **Scan mode:** ${scan.mode}`,
    `- **Scan ID:** ${scan.id}`,
    `- **Scan date:** ${scan.createdAt}`,
    ...(scan.authorizationId ? [`- **Authorization record:** ${scan.authorizationId}`] : []),
    `- **Generated by:** ${input.generatedBy}`,
    '',
    '## Executive Summary',
    '',
    `BugSeek AI performed a ${scan.mode} security assessment of ${scan.targetUrl} and identified ` +
      `${sorted.length} finding(s). CVSS v3.1 scores are heuristic estimates and should be validated ` +
      `by a human analyst before submission.`,
    '',
    '**Severity breakdown:** ' +
      ['critical', 'high', 'medium', 'low', 'info'].map((s) => `${s}: ${counts[s] ?? 0}`).join(' · '),
    '',
  ];

  const traps = sorted.filter((f) => f.honeypotSuspect).length;
  if (traps > 0) {
    lines.push(
      `> ⚠ **${traps} observation(s) were flagged as possible honeypots/traps** and require manual verification.`,
      ''
    );
  }

  // White-box findings live in their own section (below) and are excluded
  // from the verified/hints rollups as well as the general findings list.
  const { whiteBox, rest } = splitWhiteBoxFindings(sorted);

  // ── Verified exploit chains (depth ladder) ──
  const verified = verifiedFindings(rest);
  const hints = hintFindings(rest);
  if (verified.length > 0) {
    lines.push(
      '## Verified exploit chains',
      '',
      'These findings were reproduced live by the depth ladder with benign canary probes and read-only ' +
        'evidence. "Verified" means the vulnerability was reproduced — it is not proof of exploitability ' +
        'to full impact; the ladder never executes an attack chain.',
      ''
    );
    verified.forEach((f, idx) => {
      lines.push(`### ${idx + 1}. ${f.title}`, '');
      lines.push(`**Verification:** ${verificationLabel(f)}`, '');
      chainLines(f).forEach((l) => lines.push(`- ${l}`));
      lines.push('');
    });
  }
  if (hints.length > 0) {
    lines.push(
      '## Hints (unverified)',
      '',
      'These findings could not be reproduced with a benign canary probe, or no read-only live probe ' +
        'exists for their category. Treat them as unconfirmed hints and verify manually before reporting.',
      ''
    );
    hints.forEach((f) => {
      lines.push(`- **${f.title}** (${f.severity}) — ${verificationLabel(f)}`);
    });
    lines.push('');
  }

  if (whiteBox.length > 0) {
    lines.push('## White-box analysis', '', WHITEBOX_SECTION_NOTE, '');
    whiteBox.forEach((f, idx) => {
      lines.push(
        `### W${idx + 1}. ${f.title}`,
        '',
        `**Severity:** ${f.severity.toUpperCase()}${f.cvssScore != null ? ` · **CVSS:** ${f.cvssScore.toFixed(1)}` : ''} · **Confidence:** ${f.confidence}`,
        '',
        f.description,
        '',
      );
      if (f.location) lines.push(`**Location:** ${f.location}`, '');
      if (f.evidence) lines.push('**Evidence (redacted):**', '', '```', f.evidence, '```', '');
      lines.push('**Remediation:**', '', f.remediation, '');
    });
  }

  // ── Defensive aftermath (Thread 5) ──
  // Derived from defense-verification findings when the scan ran the safe
  // defense probes; omitted entirely when it did not.
  const defensiveClasses = defensiveClassesFromFindings(sorted);
  if (defensiveClasses.length > 0) {
    lines.push(
      buildDefensiveSection({
        targetUrl: scan.targetUrl,
        scannedAt: scan.createdAt,
        classes: defensiveClasses,
      }),
      '',
    );
  }

  lines.push('## Findings', '');
  if (rest.length === 0) {
    // findingCount counts every finding in the report, white-box included:
    // an empty Findings section on its own is not a zero-finding report.
    const verdict = input.coverage
      ? coverageVerdict(input.coverage, sorted.length)
      : emptyCoverageVerdict(sorted.length);
    zeroFindingsLines(verdict).forEach((l) => lines.push(l, ''));
  }
  rest.forEach((f, idx) => {
    lines.push(
      `### ${idx + 1}. ${f.title}`,
      '',
      `**Severity:** ${f.severity.toUpperCase()}${f.cvssScore != null ? ` · **CVSS:** ${f.cvssScore.toFixed(1)}` : ''} · **Confidence:** ${f.confidence}`,
      ''
    );
    gradingNotes(f).forEach((n) => lines.push(`> ${n}`, ''));
    if (f.honeypotSuspect) {
      lines.push(
        `> ⚠ **Possible trap** (trap probability ${(f.trapProbability * 100).toFixed(0)}%) — verify manually before reporting.`,
        ''
      );
    }
    lines.push(`**Verification:** ${verificationLabel(f)}`, '');
    lines.push(f.description, '');
    if (f.cvssVector) lines.push(`\`CVSS vector: ${f.cvssVector} (estimate)\``, '');
    if (f.location) lines.push(`**Location:** ${f.location}`, '');
    if (f.evidence) lines.push('**Evidence (redacted):**', '', '```', f.evidence, '```', '');
    if (f.reproSteps.length > 0) {
      lines.push('**Reproduction steps:**', '');
      f.reproSteps.forEach((s, i) => lines.push(`${i + 1}. ${s}`));
      lines.push('');
    }
    if (f.reproduce) {
      lines.push(
        '**Reproduce (copy-paste):**',
        '',
        '```sh',
        f.reproduce.command,
        '```',
        '',
        '```http',
        f.reproduce.request,
        '```',
        '',
        `Expected: ${f.reproduce.expected}`,
        ''
      );
    }
    lines.push('**Remediation:**', '', f.remediation, '');
    if (f.suggestedFix) {
      lines.push(
        '**Suggested fix (review before applying):**',
        '',
        '```',
        f.suggestedFix,
        '```',
        ''
      );
    }
    if (f.references.length > 0) {
      lines.push('**References:**', '');
      f.references.forEach((r) => lines.push(`- ${r}`));
      lines.push('');
    }
  });

  lines.push(
    '## Appendix — Methodology & Legal',
    '',
    'This assessment was performed by BugSeek AI. Active tests were rate-limited, scope-restricted to the ' +
      'user-confirmed target, and executed only after explicit authorization confirmation. Sensitive data ' +
      'discovered during testing is redacted before storage and never exfiltrated.',
    '',
    '_Disclaimer: automated findings require human verification before submission to bug bounty programs. ' +
      'BugSeek AI is intended for authorized security testing only; users accept liability for their testing activities._'
  );

  return lines.join('\n');
}
